function fig = fig06a_spatial_frequency_fusion(cfg)
%FIG06A_SPATIAL_FREQUENCY_FUSION Figure 6(a), evidence-fusion schematic.
if nargin < 1 || isempty(cfg), cfg = setup_portable_paths(); end
fig = new_figure(cfg, [80 80 900 700]);
ax = axes(fig, 'Position', [0.06 0.12 0.88 0.78]); hold(ax, 'on');
axis(ax, [0 1 0 1]); axis(ax, 'off');
draw_flow_box(ax, [0.03 0.71 0.35 0.17], ...
    ['Spatial branch' newline 'texture + directional structure'], ...
    [0.90 0.95 1.00], cfg.colors.blue);
draw_flow_box(ax, [0.03 0.40 0.35 0.17], ...
    ['Frequency branch [36]' newline 'radial energy + directional bands + phase'], ...
    [0.96 0.92 0.98], cfg.colors.purple);
draw_flow_box(ax, [0.57 0.54 0.40 0.20], ...
    ['Normalized fusion h' newline 'rotation-tolerant +' newline ...
    'direction-sensitive evidence'], [0.90 0.97 0.91], ...
    cfg.colors.green, 'FontWeight', 'bold');
draw_arrow(ax, [0.39 0.79], [0.56 0.66], cfg.colors.blue, 1.4);
draw_arrow(ax, [0.39 0.48], [0.56 0.62], cfg.colors.purple, 1.4);
text(ax, 0.50, 0.14, ...
    'UniSpector [36] motivates spatial-frequency complementarity; no source figure is copied.', ...
    'HorizontalAlignment', 'center', 'Interpreter', 'none', ...
    'FontSize', 8.5, 'Color', cfg.colors.gray);
title(ax, '(a) Spatial-frequency evidence fusion');
add_figure_note(fig, 'simulation');
end
